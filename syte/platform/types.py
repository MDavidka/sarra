"""Value objects and enums for the Coolify-parity platform layer.

Everything here is pure data: no I/O, no imports from the rest of ``syte``.
That keeps the enums importable from the store, the API models, the pure
renderers and the tests without any circular-import dance.

String enums are used throughout (rather than ``IntEnum`` or bare constants) so
values round-trip through SQLite TEXT columns and JSON API payloads unchanged,
and so the wire format matches Coolify's own vocabulary — an operator migrating
from Coolify sees ``build_pack: "nixpacks"`` and ``status: "cancelled-by-user"``
exactly as they expect.
"""

from __future__ import annotations

import re
import secrets
import string
import uuid as _uuid
from dataclasses import dataclass, field
from datetime import UTC, datetime
from enum import Enum

# --------------------------------------------------------------------------- #
# Identifiers and timestamps
# --------------------------------------------------------------------------- #

# Coolify exposes every resource by a short opaque `uuid` in API paths rather
# than a numeric primary key, which keeps IDs non-enumerable. We copy that, but
# use a base32-ish alphabet so the value is also a legal DNS label (it ends up
# inside generated container names and preview subdomains).
_UUID_ALPHABET = "abcdefghijklmnopqrstuvwxyz0123456789"
UUID_LENGTH = 20

# Docker object names, DNS labels and Caddy matcher names all tolerate this set.
_SAFE_NAME_RE = re.compile(r"[^a-z0-9-]+")


def new_uuid(length: int = UUID_LENGTH) -> str:
    """Generate a URL/DNS-safe opaque resource identifier.

    Always starts with a letter: a purely numeric leading character is invalid
    in a DNS label, and these identifiers end up in autogenerated FQDNs.
    """
    first = secrets.choice(string.ascii_lowercase)
    rest = "".join(secrets.choice(_UUID_ALPHABET) for _ in range(max(0, length - 1)))
    return first + rest


def new_password(length: int = 24) -> str:
    """Generate a password safe to embed in connection URLs and compose files.

    Deliberately excludes characters that need percent-encoding in a URI
    userinfo section (``@ : / ? # [ ] %``) and characters that YAML or a shell
    would treat specially, because these values are interpolated into
    ``postgres://user:pass@host/db`` strings and into generated compose files.
    """
    alphabet = string.ascii_letters + string.digits
    return "".join(secrets.choice(alphabet) for _ in range(length))


def utcnow() -> str:
    """ISO-8601 UTC timestamp — matches the format used by ``syte.database``."""
    return datetime.now(UTC).isoformat()


def safe_name(value: str, *, fallback: str = "resource", limit: int = 60) -> str:
    """Normalise an operator-supplied name into a docker/DNS-safe token."""
    slug = _SAFE_NAME_RE.sub("-", (value or "").strip().lower()).strip("-")
    slug = re.sub(r"-{2,}", "-", slug)
    if not slug:
        return fallback
    if not slug[0].isalpha():
        slug = f"{fallback}-{slug}"
    return slug[:limit].strip("-") or fallback


