# Every container Syte creates carries these labels. They are the only reliable
# way to reconcile "what should be running" against "what is running" after a
# restart, and to attribute a stray container to a resource during cleanup.
LABEL_MANAGED = "syte.managed"
LABEL_RESOURCE_UUID = "syte.resource.uuid"
LABEL_RESOURCE_TYPE = "syte.resource.type"
LABEL_RESOURCE_NAME = "syte.resource.name"
LABEL_ENVIRONMENT_UUID = "syte.environment.uuid"
LABEL_PROJECT_UUID = "syte.project.uuid"
LABEL_SERVER_UUID = "syte.server.uuid"
LABEL_DEPLOYMENT_UUID = "syte.deployment.uuid"
LABEL_PULL_REQUEST = "syte.pull_request"
LABEL_CONFIG_HASH = "syte.config.hash"
LABEL_IMAGE_TAG = "syte.image.tag"

# Applied to the temporary container created during a rolling update so a
# crashed deployment leaves an obviously-disposable object behind.
LABEL_ROLLING = "syte.rolling"

MANAGED_LABEL_VALUE = "true"


def managed_labels(
    *,
    resource_uuid: str,
    resource_type: ResourceType,
    resource_name: str = "",
    environment_uuid: str = "",
    project_uuid: str = "",
    server_uuid: str = "",
    deployment_uuid: str = "",
    pull_request_id: int = 0,
    config_hash: str = "",
    image_tag: str = "",
) -> dict[str, str]:
    """Build the label map for a managed container. Empty values are dropped."""
    labels = {
        LABEL_MANAGED: MANAGED_LABEL_VALUE,
        LABEL_RESOURCE_UUID: resource_uuid,
        LABEL_RESOURCE_TYPE: resource_type.value,
        LABEL_RESOURCE_NAME: resource_name,
        LABEL_ENVIRONMENT_UUID: environment_uuid,
        LABEL_PROJECT_UUID: project_uuid,
        LABEL_SERVER_UUID: server_uuid,
        LABEL_DEPLOYMENT_UUID: deployment_uuid,
        LABEL_CONFIG_HASH: config_hash,
        LABEL_IMAGE_TAG: image_tag,
    }
    if pull_request_id:
        labels[LABEL_PULL_REQUEST] = str(pull_request_id)
    return {key: value for key, value in labels.items() if value}


