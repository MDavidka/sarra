class BuildPack(str, Enum):
    """How an application's Docker image is produced.

    Mirrors Coolify's ``BuildPackTypes``. ``RAILPACK`` is Nixpacks' successor and
    is accepted as an alias so API payloads copied from Coolify keep working;
    Syte's generator treats it as an enhanced Nixpacks.
    """

    NIXPACKS = "nixpacks"
    RAILPACK = "railpack"
    STATIC = "static"
    DOCKERFILE = "dockerfile"
    DOCKERCOMPOSE = "dockercompose"
    DOCKERIMAGE = "dockerimage"

    @property
    def generates_dockerfile(self) -> bool:
        """True when Syte synthesises the Dockerfile instead of reading one."""
        return self in {BuildPack.NIXPACKS, BuildPack.RAILPACK, BuildPack.STATIC}

    @property
    def needs_git(self) -> bool:
        """``dockerimage`` deploys a prebuilt image and needs no source tree."""
        return self is not BuildPack.DOCKERIMAGE

    @property
    def supports_rolling_update(self) -> bool:
        """Compose stacks cannot be swapped atomically, so no zero-downtime.

        This is the same limitation Coolify documents: rolling updates work for
        single-container deployments only.
        """
        return self is not BuildPack.DOCKERCOMPOSE


