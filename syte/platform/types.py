# Docker object name prefixes. The uuid suffix guarantees uniqueness even when
# two projects contain resources with the same human name.
IMAGE_PREFIX = "syte"
CONTAINER_PREFIX = "syte"


def image_name(resource_uuid: str, name: str = "") -> str:
    """Local image repository for a resource (tag is applied separately)."""
    slug = safe_name(name, fallback="app", limit=40) if name else "app"
    return f"{IMAGE_PREFIX}/{slug}-{safe_name(resource_uuid, fallback='res', limit=24)}"


def container_name(resource_uuid: str, name: str = "", *, suffix: str = "") -> str:
    """Deterministic container name for a resource.

    Deterministic (rather than random per deployment) so ``docker logs`` and
    ``docker exec`` keep working across deployments, and so the supervisor can
    find the container after a Syte restart without consulting the database.
    """
    slug = safe_name(name, fallback="app", limit=40) if name else "app"
    base = f"{CONTAINER_PREFIX}-{slug}-{safe_name(resource_uuid, fallback='res', limit=24)}"
    return f"{base}-{safe_name(suffix, fallback='x', limit=12)}" if suffix else base


def volume_name(resource_uuid: str, label: str) -> str:
    return f"{IMAGE_PREFIX}-{safe_name(resource_uuid, fallback='res', limit=24)}-{safe_name(label, fallback='data', limit=24)}"


def network_name(project_uuid: str) -> str:
    """Per-project docker network so resources in a project can talk by name."""
    return f"{IMAGE_PREFIX}-{safe_name(project_uuid, fallback='net', limit=32)}"


def deployment_uuid() -> str:
    """Deployment identifiers are longer-lived and appear in URLs."""
    return _uuid.uuid4().hex


