@dataclass(frozen=True, slots=True)
class BuildContext:
    """Everything a build pack needs to synthesise a Dockerfile.

    ``files`` is the set of repository-root-relative paths that exist in the
    source tree. Passing a plain set (rather than a ``Path``) is what keeps the
    detection logic pure and testable without touching a filesystem.
    """

    files: frozenset[str] = frozenset()
    package_json: dict[str, object] = field(default_factory=dict)
    base_directory: str = "/"
    publish_directory: str = ""
    install_command: str = ""
    build_command: str = ""
    start_command: str = ""
    static_image: str = "nginx:alpine"
    node_version: str = ""
    python_version: str = ""
    build_args: tuple[tuple[str, str], ...] = ()
    # 0 means "not specified" so build packs fall back to their language
    # default. A real default here would silently override every generator.
    port: int = 0

    def has(self, *candidates: str) -> bool:
        return any(candidate in self.files for candidate in candidates)

    def has_any_suffix(self, suffix: str) -> bool:
        return any(name.endswith(suffix) for name in self.files)


