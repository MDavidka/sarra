@dataclass(frozen=True, slots=True)
class HealthCheckConfig:
    """Container healthcheck definition.

    Fields mirror Coolify's ``health_check_*`` application columns. A container
    healthcheck is what makes rolling (zero-downtime) updates possible: the new
    container must report healthy before the old one is removed.
    """

    enabled: bool = True
    path: str = "/"
    port: int | None = None
    host: str = "127.0.0.1"
    method: str = "GET"
    scheme: str = "http"
    return_code: int = 200
    response_text: str | None = None
    interval: int = 30
    timeout: int = 30
    retries: int = 3
    start_period: int = 30
    command: str | None = None

    def probe_command(self, *, container_port: int | None = None) -> str:
        """Shell command used as the container's ``HEALTHCHECK`` test.

        A custom ``command`` always wins. Otherwise we curl the configured
        endpoint. ``--noproxy '*'`` prevents a proxy env var leaking in from the
        image and making the probe check the wrong host, and ``-f`` turns a
        non-2xx response into a non-zero exit so docker marks it unhealthy.
        """
        if self.command:
            return self.command
        port = self.port or container_port or 80
        url = f"{self.scheme}://{self.host}:{port}{self.path or '/'}"
        method = (self.method or "GET").upper()
        parts = [
            "curl",
            "-f",
            "-s",
            "-S",
            "--noproxy",
            "'*'",
            "-o",
            "/dev/null",
            "-X",
            method,
            "--max-time",
            str(max(1, self.timeout)),
            f"'{url}'",
        ]
        return " ".join(parts)

    def docker_args(self, *, container_port: int | None = None) -> list[str]:
        """``docker run`` flags implementing this healthcheck."""
        if not self.enabled:
            return ["--no-healthcheck"]
        return [
            "--health-cmd",
            self.probe_command(container_port=container_port),
            "--health-interval",
            f"{max(1, self.interval)}s",
            "--health-timeout",
            f"{max(1, self.timeout)}s",
            "--health-retries",
            str(max(1, self.retries)),
            "--health-start-period",
            f"{max(0, self.start_period)}s",
        ]

    def compose_healthcheck(self, *, container_port: int | None = None) -> dict[str, object]:
        """Equivalent block for a compose service definition."""
        if not self.enabled:
            return {"disable": True}
        return {
            "test": ["CMD-SHELL", self.probe_command(container_port=container_port)],
            "interval": f"{max(1, self.interval)}s",
            "timeout": f"{max(1, self.timeout)}s",
            "retries": max(1, self.retries),
            "start_period": f"{max(0, self.start_period)}s",
        }

    @classmethod
    def from_row(cls, row: dict[str, object]) -> HealthCheckConfig:
        """Build from a ``platform_applications`` row (or any dict subset)."""

        def _int(key: str, default: int) -> int:
            raw = row.get(key)
            try:
                return int(raw)  # type: ignore[arg-type]
            except (TypeError, ValueError):
                return default

        port_raw = row.get("health_check_port")
        try:
            port = int(port_raw) if port_raw not in (None, "", 0) else None
        except (TypeError, ValueError):
            port = None

        return cls(
            enabled=bool(row.get("health_check_enabled", True)),
            path=str(row.get("health_check_path") or "/"),
            port=port,
            host=str(row.get("health_check_host") or "127.0.0.1"),
            method=str(row.get("health_check_method") or "GET"),
            scheme=str(row.get("health_check_scheme") or "http"),
            return_code=_int("health_check_return_code", 200),
            response_text=(str(row["health_check_response_text"])
                           if row.get("health_check_response_text") else None),
            interval=_int("health_check_interval", 30),
            timeout=_int("health_check_timeout", 30),
            retries=_int("health_check_retries", 3),
            start_period=_int("health_check_start_period", 30),
            command=(str(row["health_check_command"])
                     if row.get("health_check_command") else None),
        )


# Values meaning "no limit" — accepted for every limits_* field so an operator
# can explicitly opt out of a cap. Mirrors syte.docker_deploy._UNLIMITED.
UNLIMITED_VALUES = frozenset({"", "0", "0b", "none", "unlimited", "off", "-1"})


@dataclass(frozen=True, slots=True)
class ResourceLimits:
    """CPU/memory caps applied to a container.

    Defaults are empty (inherit the daemon default) rather than the aggressive
    1g/1cpu that ``syte.docker_deploy`` hardcodes, because a managed database or
    a compose service legitimately needs more than an app container. The caller
    decides; ``syte.platform.service`` fills in server-level defaults.
    """

    memory: str = ""
    memory_swap: str = ""
    memory_swappiness: int | None = None
    memory_reservation: str = ""
    cpus: str = ""
    cpuset: str = ""
    cpu_shares: int | None = None
    pids_limit: int | None = None

    @staticmethod
    def _is_set(value: str) -> bool:
        return str(value or "").strip().lower() not in UNLIMITED_VALUES

    def docker_args(self) -> list[str]:
        """``docker run`` flags for the configured caps only."""
        args: list[str] = []
        if self._is_set(self.memory):
            args += ["--memory", self.memory.strip()]
        if self._is_set(self.memory_swap):
            args += ["--memory-swap", self.memory_swap.strip()]
        if self.memory_swappiness is not None and 0 <= self.memory_swappiness <= 100:
            args += ["--memory-swappiness", str(self.memory_swappiness)]
        if self._is_set(self.memory_reservation):
            args += ["--memory-reservation", self.memory_reservation.strip()]
        if self._is_set(self.cpus):
            args += ["--cpus", self.cpus.strip()]
        if self._is_set(self.cpuset):
            args += ["--cpuset-cpus", self.cpuset.strip()]
        if self.cpu_shares and self.cpu_shares > 0:
            args += ["--cpu-shares", str(self.cpu_shares)]
        if self.pids_limit and self.pids_limit > 0:
            args += ["--pids-limit", str(self.pids_limit)]
        return args

    @classmethod
    def from_row(cls, row: dict[str, object]) -> ResourceLimits:
        def _opt_int(key: str) -> int | None:
            raw = row.get(key)
            if raw in (None, ""):
                return None
            try:
                return int(raw)  # type: ignore[arg-type]
            except (TypeError, ValueError):
                return None

        return cls(
            memory=str(row.get("limits_memory") or ""),
            memory_swap=str(row.get("limits_memory_swap") or ""),
            memory_swappiness=_opt_int("limits_memory_swappiness"),
            memory_reservation=str(row.get("limits_memory_reservation") or ""),
            cpus=str(row.get("limits_cpus") or ""),
            cpuset=str(row.get("limits_cpuset") or ""),
            cpu_shares=_opt_int("limits_cpu_shares"),
            pids_limit=_opt_int("limits_pids"),
        )


@dataclass(frozen=True, slots=True)
class DomainRoute:
    """One parsed entry from a resource's FQDN list.

    Coolify's ``fqdn`` column is a comma-separated list of URLs where each entry
    may carry a path and an explicit upstream port, e.g.::

        https://app.example.com,https://api.example.com/v1:8080

    Splitting that into structured routes is what lets the proxy layer emit
    path-scoped ``handle`` blocks instead of one dumb host block.
    """

    hostname: str
    port: int
    path: str = "/"
    scheme: str = "https"

    @property
    def is_root_path(self) -> bool:
        return self.path in ("", "/")

    @property
    def url(self) -> str:
        suffix = "" if self.is_root_path else self.path
        return f"{self.scheme}://{self.hostname}{suffix}"


@dataclass(frozen=True, slots=True)
class PortMapping:
    """A ``host:container`` port publication."""

    host_port: int
    container_port: int
    protocol: str = "tcp"

    def docker_arg(self) -> str:
        suffix = "" if self.protocol == "tcp" else f"/{self.protocol}"
        return f"{self.host_port}:{self.container_port}{suffix}"


@dataclass(frozen=True, slots=True)
class VolumeMount:
    """Persistent storage attached to a container."""

    kind: VolumeKind
    name: str
    mount_path: str
    host_path: str = ""
    content: str = ""
    is_directory: bool = False

    def docker_arg(self) -> str:
        """Source spec for ``-v``.

        Named volumes survive container recreation, which is the whole point of
        preferring them over bind mounts for database data.
        """
        if self.kind is VolumeKind.VOLUME:
            return f"{self.name}:{self.mount_path}"
        return f"{self.host_path or self.name}:{self.mount_path}"


