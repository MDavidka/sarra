def test_spa_frameworks_auto_route_to_static_pack() -> None:
    """Coolify's docs tell you to switch manually; Syte detects it."""
    context = ctx(
        ["package.json", "index.html"],
        {"devDependencies": {"vite": "5"}, "scripts": {"build": "vite build"}},
    )
    assert is_static_output(context)
    plan = resolve_build_plan(BuildPack.NIXPACKS, context)
    assert plan.build_pack is BuildPack.STATIC
    assert plan.exposed_port == 80
    assert "nginx" in plan.dockerfile
    assert any("static build pack automatically" in note for note in plan.notes)


def test_server_rendered_framework_is_not_routed_to_static() -> None:
    context = ctx(
        ["package.json"],
        {"dependencies": {"next": "14"}, "scripts": {"build": "next build", "start": "next start"}},
    )
    assert not is_static_output(context)
    assert resolve_build_plan(BuildPack.NIXPACKS, context).build_pack is BuildPack.NIXPACKS


def test_astro_with_start_script_stays_server_rendered() -> None:
    context = ctx(
        ["package.json"],
        {"dependencies": {"astro": "4"}, "scripts": {"build": "astro build", "start": "node ./dist/server/entry.mjs"}},
    )
    assert not is_static_output(context)


def test_static_nginx_config_contains_no_single_quotes() -> None:
    """The config is emitted inside a shell single-quoted `printf` argument.

    A nested single quote would terminate the shell string early and write a
    syntactically broken nginx config — the container would then exit on start.
    """
    plan = resolve_build_plan(BuildPack.STATIC, ctx(["index.html"]))
    printf_lines = [line for line in plan.dockerfile.splitlines() if "printf" in line]
    assert printf_lines
    # shlex parsing succeeding proves the quoting is balanced.
    tokens = shlex.split(printf_lines[0])
    assert "server {" in tokens
    assert any("try_files" in token for token in tokens)


def test_static_spa_fallback_only_for_built_frontends() -> None:
    spa = resolve_build_plan(
        BuildPack.STATIC,
        ctx(["package.json", "index.html"], {"devDependencies": {"vite": "5"}, "scripts": {"build": "x"}}),
    )
    plain = resolve_build_plan(BuildPack.STATIC, ctx(["index.html"]))
    assert "/index.html;" in spa.dockerfile
    assert "=404;" in plain.dockerfile


def test_plain_static_skips_the_node_toolchain() -> None:
    plan = resolve_build_plan(BuildPack.STATIC, ctx(["index.html"]))
    assert "node:" not in plan.dockerfile


