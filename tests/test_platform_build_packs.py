def test_application_row_overrides_beat_detection() -> None:
    app = {
        "ports_exposes": "9999",
        "publish_directory": "out",
        "install_command": "npm i --legacy-peer-deps",
        "build_command": "npm run export",
        "static_image": "nginx:1.27-alpine",
    }
    context = build_context_from_application(
        app,
        files=frozenset({"package.json", "index.html"}),
        package_json={"devDependencies": {"vite": "5"}, "scripts": {"build": "vite build"}},
    )
    dockerfile = resolve_build_plan(BuildPack.STATIC, context).dockerfile
    assert "npm i --legacy-peer-deps" in dockerfile
    assert "npm run export" in dockerfile
    assert "/app/out" in dockerfile
    assert "nginx:1.27-alpine" in dockerfile


def test_explicit_port_overrides_language_default() -> None:
    plan = resolve_build_plan(BuildPack.NIXPACKS, ctx(["go.mod"], port=7000))
    assert plan.exposed_port == 7000
    assert "EXPOSE 7000" in plan.dockerfile
    assert DEFAULT_PORTS["go"] != 7000


def test_unparseable_ports_exposes_falls_back_to_detection() -> None:
    context = build_context_from_application({"ports_exposes": "not-a-port"})
    assert context.port == 0


def test_build_args_are_exposed_as_arg_and_env() -> None:
    """Vite and Next only read process.env, so ARG alone is not enough."""
    plan = resolve_build_plan(
        BuildPack.NIXPACKS,
        ctx(["go.mod"], build_args=(("API_URL", "https://x"), ("BAD NAME", "y"))),
    )
    assert "ARG API_URL" in plan.dockerfile
    assert "ENV API_URL=$API_URL" in plan.dockerfile
    assert "BAD NAME" not in plan.dockerfile


