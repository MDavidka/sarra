LANGUAGE_CASES: dict[str, tuple[list[str], dict, str, int]] = {
    "next-pnpm": (
        ["package.json", "pnpm-lock.yaml", "next.config.js"],
        {"dependencies": {"next": "14"}, "scripts": {"build": "next build", "start": "next start"}},
        "node", 3000,
    ),
    "express-yarn": (
        ["package.json", "yarn.lock", "server.js"],
        {"dependencies": {"express": "4"}}, "node", 3000,
    ),
    "django": (["manage.py", "requirements.txt", "proj/wsgi.py"], {}, "python", 8000),
    "fastapi-uv": (["pyproject.toml", "uv.lock", "app/main.py"], {}, "python", 8000),
    "go": (["go.mod", "go.sum", "main.go"], {}, "go", 8080),
    "rust": (["Cargo.toml", "src/main.rs"], {"cargo_name": "svc"}, "rust", 8080),
    "laravel": (["composer.json", "artisan", "public/index.php"], {}, "php", 80),
    "rails": (["Gemfile", "config/application.rb", "bin/rails"], {}, "ruby", 3000),
    "maven": (["pom.xml"], {}, "java", 8080),
    "gradle": (["build.gradle", "gradlew"], {}, "java", 8080),
    "phoenix": (["mix.exs", "config/runtime.exs"], {}, "elixir", 4000),
    "dotnet": (["Api.csproj", "Program.cs"], {}, "dotnet", 8080),
    "bun": (["bun.lockb", "index.ts"], {}, "bun", 3000),
    "deno": (["deno.json", "main.ts"], {}, "deno", 8000),
    "plain-html": (["index.html", "style.css"], {}, "static", 80),
}


@pytest.mark.parametrize("label", sorted(LANGUAGE_CASES))
def test_detect_language_and_default_port(label: str) -> None:
    files, package_json, language, port = LANGUAGE_CASES[label]
    context = ctx(files, package_json)
    assert detect_language(context) == language
    plan = resolve_build_plan(BuildPack.NIXPACKS, context)
    assert plan.exposed_port == port
    assert f"EXPOSE {port}" in plan.dockerfile


@pytest.mark.parametrize("label", sorted(LANGUAGE_CASES))
def test_generated_dockerfiles_are_well_formed(label: str) -> None:
    files, package_json, _language, _port = LANGUAGE_CASES[label]
    plan = resolve_build_plan(BuildPack.NIXPACKS, ctx(files, package_json))
    dockerfile = plan.dockerfile
    assert dockerfile.startswith("# Generated by Syte build packs")
    assert dockerfile.endswith("\n")
    assert "FROM " in dockerfile
    assert "CMD " in dockerfile


@pytest.mark.parametrize("label", sorted(LANGUAGE_CASES))
def test_generated_runtimes_listen_on_all_interfaces(label: str) -> None:
    """Binding localhost inside a container is the top cause of Bad Gateway.

    Language runtimes get an explicit ``0.0.0.0``. The nginx and Apache images
    already listen on every interface via their own config, so for those the
    invariant is that we did not narrow it — asserting a literal ``0.0.0.0``
    there would be testing for something that should not be present.
    """
    files, package_json, _language, _port = LANGUAGE_CASES[label]
    dockerfile = resolve_build_plan(BuildPack.NIXPACKS, ctx(files, package_json)).dockerfile

    if "apache2-foreground" in dockerfile:
        assert "127.0.0.1" not in dockerfile
    elif "nginx" in dockerfile:
        assert "listen 80;" in dockerfile
        assert "listen [::]:80;" in dockerfile
    else:
        assert "0.0.0.0" in dockerfile


def test_detect_language_raises_actionable_error() -> None:
    with pytest.raises(BuildPackError) as excinfo:
        detect_language(ctx(["README.md", "LICENSE"]))
    message = str(excinfo.value)
    assert "Base Directory" in message
    assert "dockerfile" in message


def test_package_manager_prefers_corepack_declaration_over_lockfile() -> None:
    # A stale package-lock.json next to a `packageManager` field is common after
    # a migration; the explicit declaration must win.
    context = ctx(["package.json", "package-lock.json"], {"packageManager": "pnpm@9.1.0"})
    assert detect_node_package_manager(context) == "pnpm"


