def test_scan_context_skips_heavy_directories(tmp_path: Path) -> None:
    (tmp_path / "package.json").write_text(json.dumps({"dependencies": {"express": "4"}}))
    (tmp_path / "server.js").write_text("x")
    for skipped in ("node_modules", ".git", "dist", "__pycache__"):
        (tmp_path / skipped).mkdir()
        (tmp_path / skipped / "junk").write_text("x")

    files, package_json = scan_context(tmp_path)
    assert "package.json" in files
    assert "server.js" in files
    assert not any(name.startswith(("node_modules/", ".git/", "dist/")) for name in files)
    assert package_json["dependencies"] == {"express": "4"}


def test_scan_context_honours_base_directory(tmp_path: Path) -> None:
    (tmp_path / "frontend").mkdir()
    (tmp_path / "frontend" / "package.json").write_text(json.dumps({"name": "fe"}))
    (tmp_path / "backend").mkdir()
    (tmp_path / "backend" / "go.mod").write_text("module x")

    files, package_json = scan_context(tmp_path, base_directory="/frontend")
    assert files == frozenset({"package.json"})
    assert package_json["name"] == "fe"


def test_scan_context_missing_base_directory_is_empty(tmp_path: Path) -> None:
    assert scan_context(tmp_path, base_directory="/nope") == (frozenset(), {})


def test_scan_context_tolerates_malformed_package_json(tmp_path: Path) -> None:
    """Should degrade to "Node, no framework" rather than fail the deployment."""
    (tmp_path / "package.json").write_text("{not json")
    files, package_json = scan_context(tmp_path)
    assert "package.json" in files
    assert package_json == {}
    assert detect_language(BuildContext(files=files, package_json=package_json)) == "node"


def test_scan_context_extracts_cargo_crate_name(tmp_path: Path) -> None:
    (tmp_path / "Cargo.toml").write_text('[package]\nname = "cool-svc"\nversion = "0.1.0"\n')
    _files, package_json = scan_context(tmp_path)
    assert package_json["cargo_name"] == "cool-svc"
    plan = resolve_build_plan(BuildPack.NIXPACKS, ctx(["Cargo.toml"], package_json))
    assert "/app/cool-svc" in plan.dockerfile


def test_detect_dockerfile_prefers_explicit_location(tmp_path: Path) -> None:
    (tmp_path / "Dockerfile").write_text("FROM scratch")
    (tmp_path / "deploy").mkdir()
    (tmp_path / "deploy" / "Dockerfile.web").write_text("FROM alpine")

    assert detect_dockerfile(tmp_path) == tmp_path / "Dockerfile"
    assert (
        detect_dockerfile(tmp_path, location="/deploy/Dockerfile.web")
        == tmp_path / "deploy" / "Dockerfile.web"
    )
    assert detect_dockerfile(tmp_path, base_directory="/deploy") is None


def test_detect_compose_file_checks_conventional_names(tmp_path: Path) -> None:
    assert detect_compose_file(tmp_path) is None
    (tmp_path / "compose.yaml").write_text("services: {}")
    assert detect_compose_file(tmp_path) == tmp_path / "compose.yaml"
