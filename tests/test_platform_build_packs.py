"""Tests for the build pack engine — detection, generated Dockerfiles, scanning.

These replace Syte's previous hard requirement for a hand-written Dockerfile
(``syte.deployment._resolve_deploy`` refuses to deploy without one), so the
coverage here is deliberately broad: one case per supported language plus the
override and failure paths.
"""

from __future__ import annotations

import json
import shlex
from pathlib import Path

import pytest

from syte.platform.build_packs import (
    DEFAULT_PORTS,
    BuildPackError,
    build_context_from_application,
    detect_compose_file,
    detect_dockerfile,
    detect_language,
    detect_node_framework,
    detect_node_package_manager,
    detect_python_manager,
    is_static_output,
    node_install_command,
    node_start_command,
    python_start_command,
    resolve_build_plan,
    scan_context,
)
from syte.platform.types import BuildContext, BuildPack


def ctx(files: list[str], package_json: dict | None = None, **kwargs) -> BuildContext:
    return BuildContext(files=frozenset(files), package_json=package_json or {}, **kwargs)


